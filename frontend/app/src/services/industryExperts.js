/** 过滤并检索内置行业专家包（56+） */
export function filterCuratedPacks({ category = 'all', query = '' } = {}) {
  const q = String(query || '').trim().toLowerCase()
  const res = []
  for (let i = 0; i < _PACK_INDEX.length; i++) {
    const { pack, hay } = _PACK_INDEX[i]
    if (category && category !== 'all' && pack.category !== category) continue
    if (q && !hay.includes(q)) continue
    res.push(pack)
  }
  return res
}

