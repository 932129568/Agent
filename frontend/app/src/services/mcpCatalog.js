const _MCP_INDEX = CURATED_MCP_SERVERS.map((m) => ({
  item: m,
  hay: [m.id, m.serverKey, m.name, m.categoryLabel, m.badge, m.command, m.description, m.sourceRepo].join(' ').toLowerCase(),
}))

export function filterCuratedMcpServers({ category = 'all', query = '' } = {}) {
  const q = String(query || '').trim().toLowerCase()
  const out = []
  for (let i = 0; i < _MCP_INDEX.length; i++) {
    const { item, hay } = _MCP_INDEX[i]
    if (category && category !== 'all' && item.category !== category) continue
    if (q && !hay.includes(q)) continue
    out.push(item)
  }
  return out
}
