/**
 * 岛层打包：esbuild → 单一 IIFE，全局只暴露 `HarborIsland`。
 *
 * 与 Node 27 基线一致：生产模式、无 dev 分支残留（避免 file:// 下 process 未定义），
 * CSS 以 text loader 内联，产物零外部资源。
 */
import { build } from 'esbuild'
import { statSync } from 'node:fs'

const result = await build({
  entryPoints: ['src/index.jsx'],
  bundle: true,
  format: 'iife',
  globalName: 'HarborIsland',
  outfile: 'dist/harbor-island.iife.js',
  platform: 'browser',
  target: ['chrome110'],
  jsx: 'automatic',
  minify: true,
  legalComments: 'none',
  loader: { '.css': 'text' },
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: {
    js: '/* Harbor island layer (React) — generated by frontend/react; do not edit by hand. */',
  },
  logLevel: 'warning',
})

if (result.errors.length) {
  console.error('[island-build] 失败')
  process.exit(1)
}

const bytes = statSync('dist/harbor-island.iife.js').size
console.log('[island-build] node=%s dist/harbor-island.iife.js %d B (%s KiB)',
  process.version, bytes, (bytes / 1024).toFixed(1))
